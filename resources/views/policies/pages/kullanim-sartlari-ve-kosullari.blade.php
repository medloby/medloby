<section>
    <h2>Hesap ve yetki</h2>
    <p>Kayıt ve başvuru bilgilerinizi doğru ve güncel tutun. Her kullanıcı kendi hesabıyla işlem yapar. Şifrenizi gizli tutun ve şüpheli erişimi destek alanından bildirin. Klinik sahibi, personel erişimini kişinin görevi ve şubesiyle sınırlar ve görev bitiminde ilgili erişimi kaldırır.</p>
</section>
<section>
    <h2>Mesajlar ve dosyalar</h2>
    <p>Mesaj ve dosya paylaşımını ilgili görüşmenin amacıyla sınırlayın. Başka bir kişiye ait veri veya içeriği paylaşmadan önce gerekli yetkinizin bulunduğundan emin olun. Pazarlama amaçlı toplu mesaj, kimliğe bürünme, taciz ve sistem erişim kontrollerini aşma girişimleri yasaktır.</p>
</section>
<section>
    <h2>İçerik ve erişim incelemesi</h2>
    <p>Güvenlik riski, yanıltıcı bilgi, hasta mahremiyeti ihlali veya mevzuata aykırı içerik bildirildiğinde Medloby ilgili kaydı inceleyebilir ve gerekli ölçüde görünürlüğünü ya da erişimini sınırlandırabilir. Hesabınızla ilgili bir kararı destek kanalından incelemeye iletebilirsiniz.</p>
</section>
