<section>
    <h2>Sağlık hizmeti alırken</h2>
    <p>Hasta Hakları Yönetmeliği kapsamında sağlık hizmetlerinden adalet ve hakkaniyete uygun yararlanma, sağlık durumunuz hakkında bilgi isteme, mevzuatın tanıdığı şartlarla sağlık kuruluşunu ve personelini seçme, sağlık kayıtlarını inceleme ve mahremiyetinizin korunmasını isteme haklarınız vardır.</p>
</section>
<section>
    <h2>Tedavi hakkında karar verme</h2>
    <p>Muayene ve tedavinin niteliğini, seçeneklerini, risklerini ve takip sürecini sağlık meslek mensubuyla görüşün. Tıbbi müdahaleye ilişkin aydınlatma ve onamı sağlık kuruluşu yürütür. Kanuni istisnalar saklı kalmak üzere tedaviyi reddetme veya durdurulmasını isteme hakkınızı ilgili sağlık kuruluşuna iletebilirsiniz.</p>
</section>
<section>
    <h2>Nereye başvurabilirsiniz?</h2>
    <p>Sağlık hizmetine ilişkin bilgi ve şikâyetleri ilgili sağlık kuruluşuna, varsa hasta hakları birimine veya yetkili sağlık makamına iletebilirsiniz. Medloby hesabınız, randevu ekranı ya da platform mesajlarıyla ilgili konularda Medloby’nin destek alanını kullanabilirsiniz.</p>
</section>
