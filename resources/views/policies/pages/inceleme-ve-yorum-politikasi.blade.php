    <h2>Geri bildirim nasıl iletilir?</h2>
    <p>Bu sürümde klinik, hekim veya tedavi değerlendirmeleri destek üzerinden özel geri bildirim olarak ele alınır. İlgili işlem ve kendi deneyiminiz hakkında doğrulanabilir bilgi paylaşın. Sağlık bilgilerini ve üçüncü kişilerin kimliğini açıklamaktan kaçının.</p>
</section>
<section>
    <h2>İnceleme ve yayın ilkeleri</h2>
    <p>Medloby yanlış, yanıltıcı, teşvik karşılığı oluşturulmuş veya mahremiyeti ihlal eden içerikleri inceleme kapsamında değerlendirir. Katalogda sağlık hizmetinin reklamı olarak kullanılabilecek hasta yorumları, memnuniyet ifadeleri ve sonuç vaadi içeren anlatımlar yayımlanamaz. Bir içerik hakkında düzeltme veya inceleme talebini destek alanından iletebilirsiniz.</p>
</section>
