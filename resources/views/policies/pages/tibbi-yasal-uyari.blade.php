    <h2>Sağlık bilgileri ve tıbbi değerlendirme</h2>
    <p>Klinik, tedavi ve paket sayfaları genel bilgilendirme sağlar. Tanı, kişiye uygun tedavi kararı ve ilaç kullanımı için yetkili bir sağlık meslek mensubuna başvurun. Tedavinin uygunluğu, riskleri ve sonucu kişiye göre değişir. Teklif veya randevu kaydı sağlık kuruluşunda yapılacak değerlendirme ve onam sürecinden ayrı yürütülür.</p>
</section>
<section>
    <h2>Acil durumlar</h2>
    <p>Acil bir sağlık durumunda Türkiye’de 112 Acil Çağrı Merkezi’ni arayın veya acil sağlık hizmetine başvurun. Medloby mesajları ve randevu ekranları planlı işlemler içindir.</p>
</section>
