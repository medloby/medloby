<section>
    <h2>Ödeme nasıl yürütülür?</h2>
    <p>Medloby’nin mevcut sürümünde ücret, kapora ve depozito işlemleri klinik ile hasta arasında yürütülür. Medloby’de teklif kabulü ve randevu kaydı planlama işlemidir. Ödeme yapmadan önce alıcının kimliğini, ödenecek tutarı, para birimini ve vade bilgisini ilgili klinikle yazılı olarak doğrulayın.</p>
</section>
<section>
    <h2>Depozito, belge ve iade</h2>
    <p>Klinik depozito talep ediyorsa tutarı, toplam bedele nasıl sayılacağını, iptal veya tarih değişikliği şartlarını ve uygulanabilecek iade koşullarını ödeme öncesinde açıklamalıdır. Ödeme belgesini saklayın. Ödeme, belge veya iade talebinizi bedeli tahsil eden tarafa iletebilirsiniz. Tüketici mevzuatından doğan haklarınız saklıdır.</p>
</section>
